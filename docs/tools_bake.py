# Writes the generated tables into path.js. Usage: python bake.py <par.json> <molf.json> [note]
# par.json: {"first": a, "step": s0, "fall": d, "after": x}   molf.json: {smiles: factor}
import io, json, sys, subprocess, re, datetime
R = 'C:/Work/atlas-atoms/'
def sig(x, n=3):
    from math import log10, floor
    if x == 0: return 0
    m = 10 ** (floor(log10(abs(x))) - n + 1); v = round(x / m) * m
    return int(v) if v >= 100 else round(v, 6)
par = json.load(io.open(sys.argv[1], encoding='utf8')); molf = json.load(io.open(sys.argv[2], encoding='utf8'))
note = sys.argv[3] if len(sys.argv) > 3 else ''
rounds = []; p = par['first']
for k in range(9):
    rounds.append(sig(p)); p *= max(1.05, par['step'] - par['fall'] * k)
commit = subprocess.check_output(['git', '-C', R, 'rev-parse', '--short', 'HEAD']).decode().strip()
steps = [round(max(1.05, par['step'] - par['fall'] * k), 3) for k in range(8)]
block = "// GENERATED by the measuring rig (docs/RIG.md, docs/tools_sim.js) on %s from the rules at commit %s.\n" % (datetime.date.today().isoformat(), commit)
block += "// Do not edit by hand: measure again. %s\n" % note
block += "// PAR.rounds: the number for a molecule of average size in rounds one to nine. It starts at %s and each step is\n" % sig(par['first'])
block += "// smaller than the last: %s. after: the step for every round past nine.\n" % ', '.join(str(x) for x in steps)
block += "const PAR = { rounds: %s, after: %s, last: 1.15 };\n" % (json.dumps(rounds), par.get('after', 1.2))
block += "// MOLF: what the median simulated player makes in a plain round on each molecule with the starting four reagents\n// and no equipment, over the average of all the molecules (averages of logarithms).\n"
block += "const MOLF = %s;\n" % json.dumps({k: round(v, 3) for k, v in molf.items()}, separators=(',', ':'))
f = R + 'apps/steam/js/react/path.js'; s = io.open(f, encoding='utf8').read()
i = s.index('// GENERATED'); j = s.index('// END GENERATED')
s = s[:i] + block + s[j:]
io.open(f, 'w', encoding='utf8', newline='').write(s)
for h in ['apps/steam/scheme.html', '.claude/rec.html']:
    t = io.open(R + h, encoding='utf8').read(); m = re.search(r'js/react/path\.js\?v=(\d+)', t); t = t.replace(m.group(0), 'js/react/path.js?v=%d' % (int(m.group(1)) + 1)); io.open(R + h, 'w', encoding='utf8', newline='').write(t)
print('baked', rounds, 'steps', steps, 'commit', commit)
