# Writes the generated tables into path.js. Usage: python tools_bake.py <par.json or -> <factors.json or -> [note]
# par.json: {"rounds": [nine numbers], "after": x} from tools_par.py.  factors.json: {"kindf", "assayf", "molf"} from
# tools_factors.py. A dash keeps what path.js has.
import io, json, sys, subprocess, re, datetime
R = 'C:/Work/atlas-atoms/'
def sig(x, n=3):
    from math import log10, floor
    if x == 0: return 0
    m = 10 ** (floor(log10(abs(x))) - n + 1); v = round(x / m) * m
    return int(v) if v >= 100 else round(v, 6)
f = R + 'apps/steam/js/react/path.js'; s = io.open(f, encoding='utf8').read()
i = s.index('// GENERATED'); j = s.index('// END GENERATED'); old = s[i:j]
def keep(name): return re.search(r'^const %s = .*;$' % name, old, re.M).group(0)
note = sys.argv[3] if len(sys.argv) > 3 else ''
commit = subprocess.check_output(['git', '-C', R, 'rev-parse', '--short', 'HEAD']).decode().strip()
block = "// GENERATED by the measuring rig (docs/RIG.md, docs/tools_sim.js) on %s from the rules at commit %s.\n" % (datetime.date.today().isoformat(), commit)
block += "// Do not edit by hand: measure again. %s\n" % note
block += "// PAR.rounds: the number for a plain round on a molecule of average size in rounds one to nine, each fitted to the\n// pass rate and the margin in docs/BALANCE.md together (docs/tools_par.py). after: the step for every round past nine.\n"
if sys.argv[1] != '-':
    par = json.load(io.open(sys.argv[1], encoding='utf8')); block += "const PAR = { rounds: %s, after: %s, last: 1 };\n" % (json.dumps([sig(p) for p in par['rounds']]), par.get('after', 1.5))
else: block += keep('PAR') + '\n'
block += "// MOLF: what the median simulated player makes on each molecule inside runs, over the average of all the molecules.\n// KINDF: what each kind of round makes against a plain one. ASSAYF: the same for the kind of an assay, for each of\n// the three acts, over the average of the four kinds. Fitted together by docs/tools_factors.py. The number to beat is\n// multiplied by all of them, so every kind of round and every molecule is beaten by a like margin.\n"
if sys.argv[2] != '-':
    fa = json.load(io.open(sys.argv[2], encoding='utf8'))
    block += "const MOLF = %s;\n" % json.dumps({k: round(v, 3) for k, v in fa['molf'].items()}, separators=(',', ':'))
    block += "const KINDF = %s;\n" % json.dumps({k: round(v, 3) for k, v in fa['kindf'].items()}, separators=(',', ':'))
    block += "const ASSAYF = %s;\n" % json.dumps({k: [round(x, 3) for x in v] for k, v in fa['assayf'].items()}, separators=(',', ':'))
    block += "const MOLD = { lo: 0.1, hi: 10, pow: 1 };\n"
else: block += '\n'.join(keep(n) for n in ['MOLF', 'KINDF', 'ASSAYF', 'MOLD']) + '\n'
s = s[:i] + block + s[j:]
io.open(f, 'w', encoding='utf8', newline='').write(s)
for h in ['apps/steam/scheme.html', '.claude/rec.html']:
    t = io.open(R + h, encoding='utf8').read(); m = re.search(r'js/react/path\.js\?v=(\d+)', t); t = t.replace(m.group(0), 'js/react/path.js?v=%d' % (int(m.group(1)) + 1)); io.open(R + h, 'w', encoding='utf8', newline='').write(t)
print('baked', commit)
